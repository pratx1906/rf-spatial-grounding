"""P12: results freeze. Builds docs/paper/RESULTS.md from the result files only (no hand-typed numbers); every table
names its source files. Local only (docs/paper/ is gitignored).
    python -m eval.paper.freeze
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

R = Path("runs/paper/results")
OUT = Path("docs/paper/RESULTS.md")
SETS = ["v6", "heldout_v1", "v6_W4", "v6_W5", "v6_W4_51", "v6_W5_51", "v6_Npair", "v6_M0c", "v6_M1c", "v6_M2c",
        "v6_M3c", "v6_M4c"]


def _j(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def _f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def _ci(c):
    return "" if not c else f" [{_f(c[0])}, {_f(c[1])}]"


def _summ(d: Path):
    s = _j(d / "summary.json")
    return None if s is None else (s.get("score"), s.get("ci95"), s.get("n"))


def _cell(d: Path):
    s = _summ(d)
    return "-" if s is None else f"{_f(s[0])}{_ci(s[1])}"


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12] if p.exists() else "missing"


def main() -> None:
    L = ["# Results freeze (P12)", "",
         "Generated by `python -m eval.paper.freeze` from the files under `runs/paper/results/`; no number is typed by "
         "hand. Score = mean task score; CIs are 95 % cluster bootstrap over scenario seeds unless noted. Simulation "
         "only. Narrative and incidents: `docs/superpowers/plans/2026-10-28-paper-program/LEDGER.md`.", ""]

    # 1. main matrix
    models = [("prompted 4B (base)", "P1/base"), ("expert (scripted)", "P1/expert"), ("SFT v1.1", "P1/sft11|P5/sft11"),
              ("SFT v1.4", "P1/sft14|P5/sft14"), ("RL B3 s0 (SFT v1.1 + GRPO)", "P5/rl_b3"),
              ("RL B3 s1", "P5/rl_b3s1"), ("RL A3 s0 (GRPO from base)", "P5/rl_a3")]
    cols = ["v6", "heldout_v1", "v6_W4", "v6_W5", "v6_W4_51", "v6_W5_51"]
    L += ["## 1. Main test matrix", "", "Source: `<P1|P5>/<model>_<set>/summary.json`.", "",
          "| model | " + " | ".join(cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for name, pref in models:
        row = []
        for s in cols:
            cell = "-"
            for p in pref.split("|"):
                d = R / f"{p}_{s}"
                if (d / "summary.json").exists():
                    cell = _cell(d); break
            row.append(cell)
        L.append(f"| {name} | " + " | ".join(row) + " |")
    L.append("")

    # 2. ladder
    L += ["## 2. Prompted ladder (same tools, prompt, budget)", "", "Source: `P2/<model>/<set>/summary.json`.", "",
          "| model | v6 | heldout_v1 | rfg_s200 | rfg_s200_2shot |", "|---|---|---|---|---|"]
    for m in sorted(p.name for p in (R / "P2").iterdir() if p.is_dir() and p.name.startswith("qwen")):
        L.append(f"| {m} | " + " | ".join(_cell(R / "P2" / m / s) for s in
                                           ["v6", "heldout_v1", "rfg_s200", "rfg_s200_2shot"]) + " |")
    L.append("")

    # 3. data scaling
    L += ["## 3. Data scaling (P8: SFT from base on k training seeds)", "", "Source: `P8/p8k<k>_<set>/summary.json`.",
          "", "| k seeds | v6 | heldout_v1 |", "|---|---|---|"]
    for k in [3, 6, 12, 24]:
        L.append(f"| {k} | {_cell(R / f'P8/p8k{k}_v6')} | {_cell(R / f'P8/p8k{k}_heldout_v1')} |")
    L.append("")

    # 4. RL validation curves
    L += ["## 4. GRPO validation (val400, greedy, paired vs iteration 1)", "",
          "Source: `P4/<arm>/log.jsonl`; best checkpoint `P4/<arm>/best.json`. Bootstrap over tasks (not clusters).",
          "", "| arm | iter | val score | paired delta vs iter 1 |", "|---|---|---|---|"]
    for arm in ["B3_s0", "B3_s1", "A3_s0"]:
        p = R / "P4" / arm / "log.jsonl"
        if not p.exists():
            continue
        best = (_j(R / "P4" / arm / "best.json") or {}).get("iter")
        for x in p.read_text().splitlines():
            r = json.loads(x) if x.strip() else {}
            if r.get("val_score") is None:
                continue
            v = (r.get("val") or {}).get("paired_vs_iter1") or {}
            mark = " (best)" if r.get("iter") == best else ""
            L.append(f"| {arm} | {r['iter']}{mark} | {_f(r['val_score'])} | "
                     f"{'-' if not v.get('n') else ('%+.3f' % v['delta']) + _ci(v.get('ci95'))} |")
    for g in ["B3"]:
        gj = _j(R / f"P4/gate_{g}.json")
        if gj:
            L.append(f"\nGate {g} (best checkpoint CI lower > 0): **{'PASS' if gj.get('pass') else 'FAIL'}** "
                     f"(`P4/gate_{g}.json`).")
    L.append("")

    # 5. twin failure
    L += ["## 5. Twin-failure rate on hardware-mismatch pairs (nominal ok, mismatch not ok)", "",
          "Source: `P5/pairing/<model>_Npair_vs_<M>.json` (248 pairs, seeds 15-16).", "",
          "| model | M0c (control) | M1c | M2c | M3c | M4c | M2c + sensor_consistency |", "|---|---|---|---|---|---|---|"]
    for m in ["sft11", "sft14", "rl_b3"]:
        cells = []
        for M in ["M0c", "M1c", "M2c", "M3c", "M4c"]:
            d = _j(R / f"P5/pairing/{m}_Npair_vs_{M}.json")
            cells.append("-" if d is None else _f(d.get("twin_fail_rate")))
        d = _j(R / f"P5/pairing/{m}_cons_Npair_vs_M2c.json")
        cells.append("-" if d is None else _f(d.get("twin_fail_rate")))
        L.append(f"| {m} | " + " | ".join(cells) + " |")
    L.append("")

    # 6. test-time compute
    L += ["## 6. Test-time compute (P7, RL B3 s0, rfg_s200)", "", "Source: `P7/rl_b3_rfg_s200_turns<k>/summary.json`, "
          "`P7/rl_b3_rfg_s200/summary.json` (8 turns), `P7/rl_b3_bon.json`.", "",
          "| tool-turn budget | score |", "|---|---|"]
    for k, d in [(4, "rl_b3_rfg_s200_turns4"), (8, "rl_b3_rfg_s200"), (12, "rl_b3_rfg_s200_turns12"),
                 (16, "rl_b3_rfg_s200_turns16")]:
        L.append(f"| {k} | {_cell(R / 'P7' / d)} |")
    bon = _j(R / "P7/rl_b3_bon.json")
    if bon:
        L += ["", "| samples n | verifier-picked | oracle-picked |", "|---|---|---|"]
        for n, v in sorted(((k, v) for k, v in bon.get("by_n", bon).items() if k.isdigit()), key=lambda kv: int(kv[0])):
            L.append(f"| {n} | {_f(v['verifier_bon'])} | {_f(v['oracle_bon'])} |")
    L.append("")

    # 7. pre-registered contrasts
    h = _j(R / "P9full/holm.json")
    if h:
        L += ["## 7. Pre-registered primary contrasts (Holm over 3)", "", f"Source: `P9full/holm.json` ({h['method']}).",
              "", "| contrast | a vs b | n | delta | 95 % CI | p | p Holm | reject at 0.05 |", "|---|---|---|---|---|---|---|---|"]
        for k, c in h["contrasts"].items():
            ab = f"{c.get('a', c.get('model'))} vs {c.get('b', '-')}"
            L.append(f"| {k} | {ab} | {c['n']} | {c['delta']:+.4f} | {_ci(c['ci95']).strip()} | {c['p']} | "
                     f"{c['p_holm']} | {c['reject_0.05']} |")
        L.append("")

    # 8. RL behaviour + audit
    a = _j(R / "P9full/rl_audit.json")
    if a:
        keys = ["score", "n_calls", "n_refs", "abstain", "wrong_abstain", "format_failures", "zero_evidence_submit",
                "repeat_calls", "max_turns_hit", "conf_extreme"]
        L += ["## 8. Behaviour before vs after RL (val400, same tasks, iteration 1 vs best)", "",
              "Source: `P9full/rl_audit.json` (from `P4/<arm>/traj/val_iter_*.jsonl.gz`).", "",
              "| metric | " + " | ".join(f"{arm} (best {v['best_iter']})" for arm, v in a.items()) + " |",
              "|---" * (len(a) + 1) + "|"]
        for k in keys:
            L.append(f"| {k} | " + " | ".join(
                f"{v['deltas'][k]['before']:.3f} -> {v['deltas'][k]['after']:.3f} ({v['deltas'][k]['delta']:+.3f})"
                for v in a.values()) + " |")
        L += ["", "Reward-hacking audit (training iterations):", "",
              "| arm | corr(reward, score) | non-answer reward first 3 -> last 3 iters | truth-guard hits (blocked) |",
              "|---|---|---|---|"]
        for arm, v in a.items():
            t = v["train"]
            L.append(f"| {arm} | {t['corr_reward_score']} | {t['nonanswer_reward_first_last'][0]} -> "
                     f"{t['nonanswer_reward_first_last'][1]} | {t['truth_guard_hits_total']} |")
        L.append("")

    # 9. taxonomy
    tx = {m: _j(R / f"P9full/{m}_v6_taxonomy_summary.json") for m in
          ["base", "expert", "sft11", "sft14", "rl_b3", "rl_b3s1", "rl_a3"]}
    tx = {k: v for k, v in tx.items() if v}
    if tx:
        cls = sorted({c for v in tx.values() for c in v["class_share"]})
        L += ["## 9. Failure taxonomy on v6 (share of failed episodes, score < 0.8; rule-based)", "",
              "Source: `P9full/<model>_v6_taxonomy_summary.json`.", "",
              "| class | " + " | ".join(tx) + " |", "|---" * (len(tx) + 1) + "|",
              "| failed / 700 | " + " | ".join(str(v["failed"]) for v in tx.values()) + " |"]
        for c in cls:
            L.append(f"| {c} | " + " | ".join(_f(v["class_share"].get(c, 0), 3) for v in tx.values()) + " |")
        L.append("")

    # 10. unseen area (paired, pre-registered)
    na = _j(R / "NA/paired.json")
    if na:
        L += ["## 10. Unseen-area generalisation (paired, pre-registered; docs/paper/UNSEEN_AREA.md)", "",
              f"Source: `NA/paired.json`. {na['pairs']} pairs, {na['cells']} cells, questions U {na['questions']['U']} / "
              f"F {na['questions']['F']}. d = expert-normalised unseen minus familiar; margin {na['margin']}.", "",
              "| model | familiar | unseen | expert F | expert U | d [95 % CI] | H1 |", "|---|---|---|---|---|---|---|"]
        for m, v in na["results"].items():
            if "d" in v:
                L.append(f"| {m} | {v['F_mean']:.3f} | {v['U_mean']:.3f} | {v['F_expert']:.3f} | {v['U_expert']:.3f} | "
                         f"{v['d']:+.3f} {_ci(v['d_ci95']).strip()} | {'PASS' if v['H1_noninferior'] else 'FAIL'} |")
        L += ["", "| robustness variant | " + " | ".join(na["robustness"][next(iter(na["robustness"]))]) + " |",
              "|---" * (1 + len(na["robustness"][next(iter(na["robustness"]))])) + "|"]
        for vn, x in na["robustness"].items():
            L.append(f"| {vn} | " + " | ".join(f"{r['d']:+.3f} {_ci(r['ci95']).strip()}" for r in x.values()) + " |")
        L.append("")

    # 11. extra evals G1-G5
    g = _j(R / "P5/G/g_summary.json")
    if g:
        L += ["## 11. Extra evaluations G1-G5 (docs/paper/EXTRA_EVALS.md)", "",
              "Source: `P5/G/g_summary.json`; CIs cluster bootstrap over scenario seeds.", "",
              "| model | twin set | pairs | twin-fail [95 % CI] | minus control [95 % CI] | seeds 15-16 |", "|---|---|---|---|---|---|"]
        for m, v in g["G1_twin_failure_51_60"].items():
            for M in ("M0c", "M1c", "M2c"):
                if M in v:
                    dd = v.get(f"{M}_minus_M0c")
                    old = v["seeds_15_16"].get(M, {})
                    dtxt = f"{dd['delta']:+.3f} {_ci(dd['ci95']).strip()}" if dd else "-"
                    L.append(f"| {m} | {M} | {v[M]['pairs']} | {v[M]['twin_fail_rate']:.3f} {_ci(v[M]['ci95']).strip()} | "
                             f"{dtxt} | {_f(old.get('twin_fail_rate'))} |")
        b, h = g.get("G1b_consistency_51_60"), g.get("Holm_with_iii_on_51_60")
        if b:
            L += ["", f"G1b (iii) on seeds 51-60: twin-fail with consistency {b['twin_fail_with']:.3f}, without "
                      f"{b['twin_fail_without']:.3f}, delta {b['delta']:+.3f} {_ci(b['ci95']).strip()}, p {b['p']}, "
                      f"{b['pairs_changed']} of {b['pairs']} pairs changed. Holm: "
                      + ", ".join(f"{k} {v}" for k, v in h["p_holm"].items()) + "."]
        L += ["", "| model | reworded - original [95 % CI] | reworded mean | items changed |", "|---|---|---|---|"]
        for m, v in g["G2_paraphrase"].items():
            L.append(f"| {m} | {v['reworded_minus_original']:+.3f} {_ci(v['ci95']).strip()} | {v['reworded_mean']:.3f} | "
                     f"{v['changed_items']}/{v['n']} |")
        L += ["", "| hidden-world set | SFT v1.1 | SFT v1.4 | RL B3 seed 0 | RL B3 seed 1 |", "|---|---|---|---|---|"]
        for s, row in g["G4_hidden_worlds_seed_spread"].items():
            L.append(f"| {s} | " + " | ".join(_f(row.get(m, {}).get("score")) for m in ("sft11", "sft14", "rl_b3", "rl_b3s1")) + " |")
        r5 = g.get("G5_rl_b3_v6_rerun")
        if r5:
            L += ["", f"G5 rerun on v6 ({r5['n']}): RL B3 {r5['run1']:.3f} / {r5['run2']:.3f}, {r5['questions_changed']} questions "
                      f"changed score; SFT v1.4 reference {r5['sft14_reference']['run1']:.3f} / {r5['sft14_reference']['run2']:.3f}."]
        tl = g.get("H_consistency_tool_use_logged") or {}
        if tl:
            L += ["", "H2/H4 per-tool logging, with sensor_consistency offered (N + M2c, seeds 51-60):", "",
                  "| model | episodes | calling sensor_consistency | twin-fail with / without | delta [95 % CI] | tool calls |",
                  "|---|---|---|---|---|---|"]
            for m, e in tl.items():
                L.append(f"| {m} | {e['episodes']} | {e['episodes_calling_sensor_consistency']} | {_f(e.get('twin_fail_with'))} / "
                         f"{_f(e.get('twin_fail_without'))} | {e.get('delta', 0):+.3f} {_ci(e.get('ci95')).strip()} | "
                         + ", ".join(f"{k} {v}" for k, v in e["tool_call_counts"].items()) + " |")
        L.append("")

    # 12. overnight 2026-11-01: T-FIX (pre-registered), SFT seed 2, calibration/cost, tool recall
    tf = _j(R / "TFIX/twin_fix.json")
    if tf:
        L += ["## 12. Wrong-twin fix study T-FIX (pre-registered: docs/paper/TWIN_FIX_PREREG.md; results docs/paper/TWIN_FIX.md)",
              "", "Source: `TFIX/twin_fix.json`. Excess = twin-fail(M) - twin-fail(M0); reduction vs T0 paired by pair_id, "
              "cluster bootstrap over seeds 51-60. T3x and T4* are exploratory (not pre-registered).", "",
              "| arm | nominal score | M2 score | excess M2 | reduction M2 [95 % CI] | R | v6 delta [95 % CI] | calls check | F1 | F2 |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for arm, r in tf["arms"].items():
            rd = r.get("reduction_M2") or {}
            ms = r.get("mean_score") or {}
            vd = r.get("v6_delta")
            L.append(f"| {arm} | {_f(ms.get('nominal'))} | {_f(ms.get('M2'))} | {_f((r.get('excess_M2') or [None])[0])} | "
                     f"{_f(rd.get('reduction'))}{_ci(rd.get('ci95'))} | {_f(rd.get('R'), 2)} | "
                     f"{(_f(vd[0]) + _ci(vd[1])) if vd else '-'} | {_f(r.get('F5_share_calling'), 2)} | "
                     f"{r.get('F1', '-')} | {r.get('F2', '-')} |")
        L += ["", f"Holm over F1: {tf.get('holm_F1')}", ""]
    cl = _j(R / "P9full/calib_latency.json")
    if cl:
        L += ["### Calibration and cost (correct = score >= 0.8; latency under batch concurrency 24-40, not single-question)", "",
              "| policy / set | n | acc | ECE [95 % CI] | Brier | AURC | sel. acc @80 % | p50 s | tool calls | gen tokens |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for k, v in cl.items():
            L.append(f"| {k} | {v['n']} | {v['accuracy']:.3f} | {v['ece']:.3f}{_ci(v['ci95']['ece'])} | {v['brier']:.3f} | "
                     f"{v['aurc']:.3f} | {v['sel_acc_80']:.3f} | {v['latency_p50_s']} | {v['tool_calls_mean']} | {v['gen_tokens_mean']} |")
        L.append("")
    trc = _j(R / "TFIX/tool_recall_n1.json")
    if trc:
        L += ["### Tool recall vs the expert on v6 (exploratory; per-call logging)", ""]
        for m, v in trc["models"].items():
            L.append(f"{m}: mean Jaccard {v['mean_jaccard']}, distinct tools model {v['distinct_tools_model']} / expert "
                     f"{v['distinct_tools_expert']}; " + ", ".join(f"{t} {d['recall']}" for t, d in v["per_tool"].items()
                                                                   if d["recall"] is not None and d["recall"] < 0.95))
        L.append("")

    # provenance
    L += ["## Provenance", "", "| file | sha256[:12] |", "|---|---|"]
    for p in ["TFIX/twin_fix.json", "TFIX/self_calib.json", "P9full/calib_latency.json", "P5/G/g_summary.json", "NA/paired.json","P9full/holm.json", "P9full/rl_audit.json", "P7/rl_b3_bon.json", "P4/B3_s0/log.jsonl",
              "P4/B3_s1/log.jsonl", "P4/A3_s0/log.jsonl", "P4/gate_B3.json"]:
        L.append(f"| `{p}` | {_sha(R / p)} |")
    for s in ["v6", "heldout_v1"]:
        L.append(f"| `eval/frozen/{s}/tasks.jsonl` | {_sha(Path('eval/frozen') / s / 'tasks.jsonl')} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(OUT, len(L), "lines")


if __name__ == "__main__":
    main()
