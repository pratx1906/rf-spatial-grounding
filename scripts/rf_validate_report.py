"""Figures and tables for docs/RESULTS/rf_validation.md from runs/rfval/{sionna,df_crb,df_two_path}.json.

    .venv-sionna-win\\Scripts\\python scripts\\rf_validate_report.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from sim.rf import refs  # noqa: E402

RV = REPO / "runs" / "rfval"
FIG = REPO / "docs" / "RESULTS" / "figs"


def main() -> int:
    FIG.mkdir(parents=True, exist_ok=True)
    s = json.loads((RV / "sionna.json").read_text())
    crb = json.loads((RV / "df_crb.json").read_text())
    tp = json.loads((RV / "df_two_path.json").read_text())

    # two-ray over sea water at 2.44 GHz
    fig, ax = plt.subplots(figsize=(7, 3.4))
    for pol, c in (("V", "#c2410c"), ("H", "#1d4ed8")):
        r = s["B_two_ray"]["cases"][f"ism_2400/sea_water/{pol}"]
        ax.plot(r["d_m"], r["ref_db"], color=c, lw=1, label=f"two-ray, P.2040 slab, {pol}-pol")
        ax.plot(r["d_m"][::4], r["sim_db"][::4], "o", ms=3, color=c, label=f"Sionna RT, {pol}-pol")
    ax.set_xlabel("range (m)")
    ax.set_ylabel("path loss (dB)")
    ax.set_title("Sea-water ground, 2.44 GHz, mast 25 m, drone 40 m")
    ax.invert_yaxis()
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(FIG / "rfval_two_ray.png", dpi=150)
    plt.close(fig)

    # wedge: Sionna stock vs UTD hard/soft vs knife edge (horizontal steel edge, V-pol)
    rows = s["D_wedge"]["bands"]["ism_2400"]["rows"]
    z = np.array([r["z"] for r in rows])
    k = 2 * math.pi * 2.44e9 / refs.C0
    php, sp = math.atan2(10, 500), math.hypot(500, 10)
    soft = []
    for zz in z:
        phi = math.atan2(zz - 20, -500) % (2 * math.pi)
        s_, r = math.hypot(500, zz - 20), math.hypot(1000, zz - 30)
        e = refs.utd_point_source_field(1.5, phi, php, sp, s_, k, False)
        if phi < math.pi + php:
            e += complex(math.cos(-k * r), math.sin(-k * r)) / r
        soft.append(-20 * math.log10(abs(e) * r))
    fig, ax = plt.subplots(figsize=(7, 3.4))
    ax.plot(z, [r["utd_db"] for r in rows], color="#15803d", lw=1.5, label="UTD hard (physics for V-pol)")
    ax.plot(z, soft, color="#64748b", lw=1, ls="--", label="UTD soft")
    ax.plot(z, [r["knife_db"] for r in rows], color="#a16207", lw=1, ls=":", label="P.526 knife edge (scalar)")
    ax.plot(z, [r["sim_db"] for r in rows], "o", ms=3, color="#b91c1c", label="Sionna RT 2.2 stock")
    pf = s["F_wedge_patched"]["cases"]["steel/horizontal/V"]["rows"]
    ax.plot([20 + p["offset_m"] for p in pf], [p["sionna_fixed_db"] for p in pf], "s", ms=5, mfc="none",
            color="#15803d", label="Sionna + envbuild.sionna_fix")
    ax.set_xlabel("receiver height (m); edge at 20 m, shadow below ~10 m")
    ax.set_ylabel("loss rel. free space (dB)")
    ax.set_title("90-degree steel edge, V-pol, 2.44 GHz")
    ax.invert_yaxis()
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "rfval_wedge.png", dpi=150)
    plt.close(fig)

    # DF vs CRB
    rr = crb["rows"]
    snr = [r["snr_db"] for r in rr]
    fig, ax = plt.subplots(figsize=(7, 3.4))
    ax.semilogy(snr, [r["crb_deg"] for r in rr], "k-", lw=1, label="CRB (4-el square, N=256)")
    ax.semilogy(snr, [r["crb_plus_grid_deg"] for r in rr], "k--", lw=1, label="CRB + 0.5 deg grid floor")
    ax.semilogy(snr, [r["rmse_ideal_deg"] for r in rr], "o-", ms=4, color="#15803d", label="engine, no impairments")
    ax.semilogy(snr, [float(np.median(r["rmse_configured_3draws_deg"])) for r in rr], "x-", ms=5, color="#b91c1c",
                label="engine as configured (median of 3 cal. draws)")
    ax.semilogy(snr, [float(np.median(r["rmse_floor20_3draws_deg"])) for r in rr], "s-", ms=4, color="#1d4ed8",
                label="configured + -20 dB model-error floor")
    ax.set_xlabel("SNR per element (dB)")
    ax.set_ylabel("bearing RMSE (deg)")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "rfval_df_crb.png", dpi=150)
    plt.close(fig)

    fs = s["A_free_space"]["bands"]
    tr = s["B_two_ray"]["cases"]
    E = s["E_wedge_polarisation"]["cases"]
    F = s["F_wedge_patched"]["cases"]
    lines = [
        "# RF validation suite (simulation physics vs closed forms)",
        "",
        "Generated by `scripts/rf_validate.py` (Sionna RT 2.2, Windows), `scripts/df_crb.py` (WSL, GPU) and "
        "`scripts/rf_validate_report.py`. Raw numbers: `runs/rfval/*.json`. References: `sim/rf/refs.py`, "
        "unit-tested against textbook values in `tests/unit/test_rf_validation_refs.py`.",
        "",
        "## Summary",
        "",
        "| Case | Reference | Result | Verdict |",
        "|---|---|---|---|",
        f"| A. Free space, 10 m-3 km, 0.9/2.44/5.8 GHz | Friis | max error {max(v['max_abs_err_db'] for v in fs.values())} dB | pass (< 0.1 dB) |",
        f"| B. Ground reflection: sea water, steel, 0.3 m concrete; V and H; 3 bands | two-ray with the ITU-R P.2040 slab coefficient | median error <= {max(v['median_err_db'] for v in tr.values()):.3f} dB, p95 <= {max(v['p95_err_db'] for v in tr.values()):.2f} dB (max {max(v['max_err_db'] for v in tr.values()):.2f} dB beside nulls) | pass |",
        f"| C. DF engine, single path | Cramer-Rao bound | without impairments RMSE = CRB with the 0.5 deg grid floor (within 1-3 %) | pass |",
        f"| D/E. Edge diffraction, stock Sionna RT 2.2 | UTD (Kouyoumjian-Pathak), Luebbers | soft and hard coefficients exchanged; lossy wedges at the conductor-hard level | **defect found** |",
        f"| F. Edge diffraction with `envbuild/sionna_fix.py` | UTD (steel), Luebbers (concrete), lit-region total field | max median error {max(v['median_err_db'] for v in F.values()):.3f} dB | pass |",
        "",
        "## A-B. Propagation and reflection",
        "",
        "![two-ray](figs/rfval_two_ray.png)",
        "",
        "- Over sea water |Gamma_H| is close to 1 at every grazing angle, so H-pol shows deep interference nulls; "
        "V-pol has a pseudo-Brewster minimum near 7 deg grazing, so its nulls are shallow at these geometries. "
        "Sionna reproduces both to hundredths of a dB.",
        "- Sionna applies a radio material's thickness as a slab (P.2040 eq. 37-38), so 0.3 m concrete is compared "
        "with the slab formula, not a half-space.",
        "",
        "## C. DF engine against the Cramer-Rao bound",
        "",
        "![crb](figs/rfval_df_crb.png)",
        "",
        "| SNR dB | CRB deg | CRB+grid | no impairments | configured (3 cal. draws) | 180-deg flips | with -20 dB floor |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rr:
        lines.append(f"| {r['snr_db']} | {r['crb_deg']} | {r['crb_plus_grid_deg']} | {r['rmse_ideal_deg']} | "
                     f"{', '.join(map(str, r['rmse_configured_3draws_deg']))} | {r['flip_share_configured']:.2%} | "
                     f"{', '.join(map(str, r['rmse_floor20_3draws_deg']))} |")
    lines += [
        "",
        "- The MUSIC/Bartlett engine is statistically efficient: without impairments it sits on the bound.",
        "- At 15 dB one trial in 4,500 has a gross error with and without the floor (noise-driven); it is visible "
        "as 4.5 deg RMSE in one calibration draw.",
        "- **Finding:** with the configured calibration residuals (0.3 dB gain, 1 deg phase, 2 deg inter-chip), "
        "forward-backward averaging turns the gain mismatch into a spurious eigenvalue about 29 dB below the signal. "
        "Above about 15 dB SNR the MDL estimator calls it a second source, which gives 1.7-30 deg RMSE and up to "
        "2 % gross errors.",
        "- **Fix:** eigenvalues more than 20 dB below the largest count as noise (`processing.model_error_floor_db`). "
        "This brings the high-SNR error to 0.35-0.64 deg with no gross errors.",
        "  - It leaves the resolution of real coherent second paths unchanged (table below).",
        "  - It is off in the v1 scenario sets (kept byte-identical for comparability) and on in the v2 sets.",
        "",
        "| SNR / second path | top peak = direct (plain, floor) | reflection found (plain, floor) |",
        "|---|---|---|",
    ]
    for kk, v in tp.items():
        lines.append(f"| {kk} | {v['plain']['top_is_direct']}, {v['floor20']['top_is_direct']} | "
                     f"{v['plain']['reflection_found']}, {v['floor20']['reflection_found']} |")
    lines += [
        "",
        "## D-F. Edge diffraction",
        "",
        "![wedge](figs/rfval_wedge.png)",
        "",
        "Which UTD coefficient stock Sionna RT 2.2 applies (90-degree steel edge, 2.44 GHz):",
        "",
        "| Edge / polarisation | physics (KP) | stock Sionna matches | error to the matched one |",
        "|---|---|---|---|",
    ]
    for kk, v in E.items():
        lines.append(f"| {kk} | {v['physics_expects']} | {v['sionna_matches']} | {v['median_err_to_match_db']} dB |")
    lines += [
        "",
        "- **Steel (perfect conductor):** stock Sionna exchanges the soft (E parallel to the edge) and hard "
        "coefficients on both horizontal and vertical edges.",
        "- **0.3 m concrete:** stock Sionna gives about 34 dB excess loss for both polarisations. Luebbers' "
        "lossy-wedge UTD gives 49-54 dB, so stock Sionna under-states deep-shadow loss by 15-20 dB.",
        "- **Cause:** `RadioMaterial._diffraction_matrix` assembles R_0 (d1 - d4) + R_n (d2 - d3) in rotated face "
        "bases and forces R_n = -I for exterior angles > pi + phi'.",
        "- **Fix:** `envbuild/sionna_fix.py` (patch id `sionna-2.2-utd-luebbers-v2`).",
        "  - It keeps Sionna's geometry, transition terms and slab coefficients.",
        "  - It assembles the textbook form: D_s,h = d1 + d2 + R_n d3 + R_0 d4, with TE for soft and TM for hard, in "
        "KP's edge-fixed bases.",
        "  - Checked against UTD, Luebbers and the lit-region total field (phase), it agrees within:",
        "",
        "| Material / edge / pol | coefficient | median error dB | max error dB |",
        "|---|---|---|---|",
    ]
    for kk, v in F.items():
        lines.append(f"| {kk} | {v['coefficient']} | {v['median_err_db']} | {v['max_err_db']} |")
    lines += [
        "",
        "**Notes:**",
        "",
        "- **Concrete:** the agreement shows the code implements Luebbers exactly. Luebbers itself is a published "
        "heuristic for lossy wedges, checked against measurements in the literature, not by us.",
        "- **Thin screens:** Sionna finds no diffracted path behind a 0.2 m thin screen, because its edge search "
        "needs ray hits on the faces next to the edge. Site objects are tanks, buildings and hulls; this is a "
        "documented limitation, not a site error.",
        "- **Source exactly level with the edge:** with the source at exactly the screen-top height, the edge search "
        "also degenerates (0 paths). The canonical case uses a source 10 m above the edge.",
        "- **Impact on the site caches:**",
        "  - For drones at 5-15 m the strongest arrival is a diffraction in 4-30 % of cells (S4/S5 most); at 40 m and "
        "above it is under 10 %.",
        "  - Caches traced from RF phase 2 on use the fix and record the patch id in their manifests.",
        "  - Phase-1 and v1 caches stay as they were, for comparability. Their diffraction levels carry this defect.",
    ]
    (REPO / "docs" / "RESULTS" / "rf_validation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/RESULTS/rf_validation.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
